"""Pure offline validation of Qwen LoRA sources. Never trains mock weights."""
import json
from pathlib import Path
from tempfile import TemporaryDirectory
import unittest

from williams_ai.book_rules import registry
from williams_ai.private_lora import (
    checked_private_training_data,_tokenized,train_private_lora
)


def candidates():
    books={x["id"]:x for x in registry()["books"]}
    rules={ed:sorted((r for r in registry()["rule_cards"]
                      if r["source"]==ed and r["status"]=="REVIEWED_PAGES"),
                     key=lambda v:v["id"])[:3]
           for ed in ("TC1","NTD","TC2","COURSE")}
    items=[]
    for i in range(100):
        ed=("TC1","NTD","TC2","COURSE")[i%4]
        rule=rules[ed][0 if i<64 else 1 if i<82 else 2]
        items.append({
            "case_id":f"approved-{i:04d}",
            "edition":ed,
            "rule_id":rule["id"],
            "pdf_page":rule["pdf_pages"][0],
            "source_sha256":books[ed]["sha256"],
            "question":f"Вопрос {i:04d}: объясни правило {rule['id']} и его ограничение по закрытым барам",
            "answer":f"Ответ {i:04d}: источником служит {rule['id']}, сигнал не равен исполнению биржевой заявки.",
            "review_status":"INDEPENDENT_EXPERT_REVIEWED",
            "reviewer_id":"expert-001",
            "split":("train" if i<64 else "validation" if i<82 else "test"),
        })
    return items


class OfflineIndependentSupervisionTests(unittest.TestCase):
    def setUp(self):
        self.temp=TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root=Path(self.temp.name)
        self.data=self.root/"approved.jsonl"

    def save(self,items):
        self.data.write_text(
            "\n".join(json.dumps(x,ensure_ascii=False) for x in items)+"\n",
            encoding="utf-8")

    def test_valid_four_book_reviewed_split_keeps_holdout_out_of_trainer(self):
        self.save(candidates())
        checked=checked_private_training_data(self.data)
        self.assertEqual(checked["counts"],{"train":64,"validation":18,"test":18})
        self.assertEqual(set(checked["source_editions"]),
                         {"TC1","NTD","TC2","COURSE"})
        self.assertEqual(len(checked["items_for_local_fit"]["train"]),64)
        self.assertFalse(any(x["split"]=="test" for x in
            checked["items_for_local_fit"]["train"]+
            checked["items_for_local_fit"]["validation"]))
        self.assertTrue(checked["reviewer_declaration_not_independently_verified"])
        self.assertTrue(checked["individual_book_rules_never_cross_splits"])

    def test_fake_student_or_wrong_page_never_reaches_training(self):
        for key,value in (
            ("review_status","AUTOGENERATED_CONFIDENT"),
            ("source_sha256","a"*64),
            ("pdf_page",9999),
            ("rule_id","UNKNOWN.NOT_BOOK"),
        ):
            data=candidates()
            data[0][key]=value
            self.save(data)
            with self.subTest(key=key):
                with self.assertRaises(ValueError):
                    checked_private_training_data(self.data)
        x=candidates()
        x[75]["question"]=x[0]["question"]
        self.save(x)
        with self.assertRaisesRegex(ValueError,"DUPLICATE_QUESTION"):
            checked_private_training_data(self.data)

    def test_book_rule_not_shared_between_train_and_validation(self):
        rows=candidates()
        rows[64]["rule_id"]=rows[0]["rule_id"]
        rows[64]["pdf_page"]=rows[0]["pdf_page"]
        rows[64]["edition"]=rows[0]["edition"]
        rows[64]["source_sha256"]=rows[0]["source_sha256"]
        self.save(rows)
        with self.assertRaisesRegex(ValueError,"SAME_BOOK_RULE_LEAKED"):
            checked_private_training_data(self.data)

    def test_dataset_can_not_be_written_inside_public_repository(self):
        with self.assertRaisesRegex(ValueError,"OUTSIDE_GIT"):
            checked_private_training_data(
                Path(__file__).resolve().parents[1]/"docs"/"fake.jsonl")

    def test_requires_four_editions_and_sufficient_independent_examples(self):
        self.save(candidates()[:60])
        with self.assertRaisesRegex(ValueError,"INSUFFICIENT_REVIEWED"):
            checked_private_training_data(self.data)
        x=candidates()
        x[65]["split"]="train"
        self.save(x)
        checked=checked_private_training_data(self.data)
        self.assertEqual(checked["counts"]["train"],65)

    def test_loss_masks_every_prompt_token_and_never_truncates_answer(self):
        tok=type("MockTokenizer",(),{
            "eos_token":"<end>",
            "apply_chat_template":lambda self,messages,tokenize,add_generation_prompt:[11,12,13],
            "encode":lambda self,text,add_special_tokens:[21,22,23],
        })()
        sample=_tokenized(candidates()[:1],tok,max_tokens=128)[0]
        self.assertEqual(sample["labels"],[-100,-100,-100,21,22,23])
        self.assertEqual(sample["input_ids"],[11,12,13,21,22,23])

    def test_wrong_source_stops_before_loading_transformers_or_gpu(self):
        self.save(candidates()[:5])
        with self.assertRaisesRegex(ValueError,"INSUFFICIENT_REVIEWED"):
            train_private_lora(
                data=self.data,model_dir=self.root/"nonexistent",
                output_dir=self.root/"outputs")

if __name__=="__main__":
    unittest.main()
